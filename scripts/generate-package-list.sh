#!/usr/bin/env bash
# Concatenate iso/packages/*.txt into iso/profile/packages.x86_64.
# Comments and blank lines are stripped, duplicates removed, order preserved.
set -euo pipefail

# shellcheck source=scripts/lib.sh
source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib.sh"

out="$PROFILE_SRC/packages.x86_64"
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

shopt -s nullglob
lists=("$PROJECT_ROOT"/iso/packages/*.txt)
shopt -u nullglob

(( ${#lists[@]} )) || die "no package lists found in iso/packages/"

{
  echo "# Generated by scripts/generate-package-list.sh from iso/packages/*.txt"
  echo "# Do not edit by hand."
  cat "${lists[@]}"
} | sed -e 's/[[:space:]]*#.*$//' -e 's/[[:space:]]\+$//' -e '/^[[:space:]]*$/d' \
  | awk '!seen[$0]++' >"$tmp"

if [[ ! -s "$tmp" ]]; then
  die "generated package list is empty"
fi

mv "$tmp" "$out"
log "wrote $out ($(grep -c . "$out") packages)"
grep -v '^#' "$out" | tr '\n' ' ' >/dev/null
