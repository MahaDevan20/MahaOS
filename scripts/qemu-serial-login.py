#!/usr/bin/env python3
"""Drive a QEMU serial console: log into the live session and record probes.

Usage: qemu-serial-login.py SOCKET LOG SUMMARY

The guest boots with console=ttyS0, so systemd spawns serial-getty@ttyS0. This
script mirrors every byte the guest writes into LOG, logs in as the live user and
runs a fixed probe list, then writes the decoded command output blocks to
SUMMARY. Exit status 2 means the login prompt never appeared.
"""
import os
import re
import socket
import sys
import time

SOCK, LOG, SUMMARY = sys.argv[1], sys.argv[2], sys.argv[3]
USER = os.environ.get("LIVE_USER", "liveuser")
PASSWORD = os.environ.get("LIVE_PASS", "live")
LOGIN_TIMEOUT = float(os.environ.get("LOGIN_TIMEOUT", "420"))
ANSI = re.compile(rb"\x1b\[[0-9;?]*[A-Za-z]|\x1b\][^\x07]*\x07|\x1b[()][B0]")

# Probes that wait for something inside the guest need more than the default.
PROBE_TIMEOUTS = {"installer-proc": 220}

COMMANDS = [
    ("cmdline", "cat /proc/cmdline"),
    ("ip-a", "ip a"),
    ("ip-brief", "ip -br a"),
    ("nmcli", "nmcli -t -f DEVICE,TYPE,STATE,CONNECTION device status"),
    ("services", "systemctl is-active sddm graphical.target"),
    ("failed-units", "systemctl --no-pager --failed"),
    ("sessions", "loginctl list-sessions --no-legend"),
    (
        "graphical-session",
        'for s in $(loginctl list-sessions --no-legend | awk \'$4=="seat0" {print $1}\'); '
        'do loginctl show-session "$s" -p Id -p Name -p Type -p Desktop -p Active; done',
    ),
    ("desktop-procs", "pgrep -af 'Hyprland|labwc|sddm|Xorg'"),
    (
        # Waits inside the guest for the auto-started installer, so a slow
        # Calamares start is not mistaken for a failure.
        "installer-proc",
        'for i in $(seq 1 90); do pgrep -x calamares >/dev/null 2>&1 && break; sleep 2; done; '
        'pgrep -af calamares || echo NO-CALAMARES-PROCESS',
    ),
    (
        "installer-windows",
        'sig=$(ls /run/user/1000/hypr 2>/dev/null | head -1); '
        'HYPRLAND_INSTANCE_SIGNATURE=$sig XDG_RUNTIME_DIR=/run/user/1000 '
        'hyprctl clients -j 2>/dev/null | grep -o "\\\"class\\\":[^,]*" | sort -u || echo NO-HYPRCTL',
    ),
    (
        "hyprland-config",
        'sig=$(ls /run/user/1000/hypr 2>/dev/null | head -1); '
        'grep -iE "config|lua|autogenerated" "/run/user/1000/hypr/$sig/hyprland.log" 2>/dev/null | tail -n 25 '
        '|| echo NO-HYPRLAND-LOG',
    ),
    ("installer-log", "tail -n 20 /tmp/mahadevanos-installer.log 2>/dev/null || echo NO-INSTALLER-LOG"),
    (
        # Calamares logs every module's errors to ~/.cache/calamares/session.log
        # (Logger.cpp: appLogDir()/session.log). It runs as root from the live
        # launcher, so the log is under /root. Any ERROR: line fails the boot test.
        "calamares-log-errors",
        'LOG=/root/.cache/calamares/session.log; '
        'if sudo test -f "$LOG"; then '
        'sudo grep -a "ERROR:" "$LOG" | tail -n 40 || echo NO-ERROR-LINES; '
        'else echo NO-CALAMARES-SESSION-LOG; fi',
    ),
    ("os-release", "grep -E '^(ID|PRETTY_NAME)=' /etc/os-release"),
]

log = open(LOG, "ab", buffering=0)
seen = b""


def connect(path, tries=240):
    for _ in range(tries):
        try:
            s = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
            s.connect(path)
            s.settimeout(0.5)
            return s
        except OSError:
            time.sleep(0.25)
    print("serial socket unavailable", file=sys.stderr)
    raise SystemExit(3)


def pump():
    """Read whatever is available and mirror it to the log."""
    global seen
    try:
        data = sock.recv(65536)
    except socket.timeout:
        return b""
    except OSError:
        return b""
    if data:
        log.write(data)
        seen += data
    return data


def wait_for(patterns, timeout, label):
    deadline = time.time() + timeout
    while time.time() < deadline:
        pump()
        for pat in patterns:
            if pat in seen:
                return pat
    print(f"timeout waiting for {label}", file=sys.stderr)
    return None


def send(text):
    sock.sendall(text.encode())


def wait_prompt(timeout, tail=4096):
    """Wait until the shell prompt is back, so input is not typed mid-command."""
    deadline = time.time() + timeout
    while time.time() < deadline:
        pump()
        if b"]$ " in seen[-(tail + 1):]:
            return True
    return False


def plain(data):
    return ANSI.sub(b"", data).decode("utf-8", "replace").replace("\r", "")


def blocks():
    text = plain(seen)
    out = []
    for name, _ in COMMANDS:
        m = re.search(
            rf"===BEGIN {re.escape(name)}===\n(.*?)\n?===END {re.escape(name)}===",
            text,
            re.S,
        )
        out.append((name, m.group(1) if m else "<no output captured>"))
    return out


sock = connect(SOCK)

if not wait_for([b"login:"], LOGIN_TIMEOUT, "login prompt"):
    plain_seen = plain(seen)
    with open(SUMMARY, "w", encoding="utf-8") as fh:
        fh.write("NO LOGIN PROMPT: the guest never reached a serial getty.\n")
        fh.write(f"serial bytes captured: {len(seen)}\n\n--- tail ---\n")
        fh.write(plain_seen[-4000:])
    raise SystemExit(2)

time.sleep(0.5)
send(f"{USER}\n")
if not wait_for([b"Password:"], 60, "password prompt"):
    raise SystemExit(2)
time.sleep(0.3)
send(f"{PASSWORD}\n")
time.sleep(3)
pump()

# A logged-in shell must echo a marker back; that proves the login worked.
send("echo LOGIN-OK-MARKER\n")
if not wait_for([b"LOGIN-OK-MARKER"], 60, "shell marker"):
    print("login did not produce a shell", file=sys.stderr)
    with open(SUMMARY, "w", encoding="utf-8") as fh:
        fh.write("LOGIN FAILED: no shell prompt after the password.\n\n")
        fh.write(plain(seen)[-4000:])
    raise SystemExit(4)
if not wait_prompt(30):
    print("shell prompt did not return after login", file=sys.stderr)

# Turn echo off: the terminal otherwise repeats every command we type, which
# makes the BEGIN/END markers ambiguous when the log is parsed.
send("stty -echo\n")
wait_prompt(15)

for name, cmd in COMMANDS:
    line = f"printf '\\n===BEGIN {name}===\\n'; {cmd}; printf '\\n===END {name}===\\n'\n"
    for attempt in (1, 2):
        time.sleep(0.6)
        send(line)
        deadline = time.time() + PROBE_TIMEOUTS.get(name, 60)
        while time.time() < deadline:
            pump()
            if b"===END %s===" % name.encode() in seen:
                break
        else:
            print(f"no output marker for {name} (attempt {attempt})", file=sys.stderr)
            continue
        break
    if not wait_prompt(20):
        print(f"prompt missing after {name}", file=sys.stderr)
    time.sleep(0.2)

pump()
with open(SUMMARY, "w", encoding="utf-8") as fh:
    fh.write(f"# Serial session probe ({USER}@ttyS0)\n\n")
    for name, body in blocks():
        fh.write(f"## {name}\n```\n{body.strip()}\n```\n\n")
print(f"wrote {LOG} and {SUMMARY}", file=sys.stderr)
